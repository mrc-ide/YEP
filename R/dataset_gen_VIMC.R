#' @title Generate_VIMC_Burden_Dataset
#'
#' @description Generate annual burden data in format used by VIMC
#'
#' @details This function is used to generate annual burden data in the format used by the Vaccine Impact
#'   Modelling Consortium (VIMC) [TBA]
#'
#' @param FOI_values Array of values of force of infection due to spillover from sylvatic reservoir by region + time
#' @param R0_values Array of values of basic reproduction number for human-human transmission by region and time
#' @param input_data List of population and vaccination data for multiple regions
#' @param template Burden data in VIMC format, with regions, years, minimum and maximum age, and life expectancy
#'   for each line
#' @param vaccine_efficacy Fractional vaccine efficacy
#' @param time_inc Time increment in days to use in model (should be either 1.0, 2.5 or 5.0 days)
#' @param mode_start Flag indicating how to set initial population immunity level in addition to vaccination \cr
#'  If mode_start = 0, only vaccinated individuals \cr
#'  If mode_start = 1, shift some non-vaccinated individuals into R to give herd immunity (stratified by age) \cr
#' @param mode_time Type of time dependence of FOI_spillover and R0 to be used: \cr
#'  If mode_time = 0, no time variation (constant values)\cr
#'  If mode_time = 1, FOI/R0 vary annually without seasonality (no. values = no. years to consider) \cr
#'  If mode_time = 2, FOI/R0 vary with monthly seasonality without inter-annual variation (no. values = 12) \cr
#'  If mode_time = 3, FOI/R0 vary with daily seasonality without inter-annual variation (no. values = 365/dt) \cr
#'  If mode_time = 4, FOI/R0 vary annually with monthly seasonality (no. values = 12*no. years to consider) \cr
#'  If mode_time = 5, FOI/R0 vary annually with daily seasonality (no. values = (365/dt)*no. years to consider)
#' @param n_reps no. stochastic repetitions
#' @param deterministic TRUE/FALSE - set model to run in deterministic mode if TRUE
#' @param p_severe_inf Probability of an infection being severe
#' @param p_death_severe_inf Probability of a severe infection resulting in death
#' @param YLD_per_case TBA
#' @param mode_div Mode of division of regions while running model. \cr
#'  If mode_div = "parallel", run all regions simultaneously in a single use of the Model_Run function;
#'  will run all years for every region \cr
#'  If mode_div = "serial", run all regions in series \cr
#'  If mode_div = "cluster", set model to run regions in parallel using cluster of nodes (see n_nodes parameter)
#' @param n_nodes no. nodes to use in parallelization (if mode_div = cluster)
#' @param seed Optional random seed value; set to NULL to omit. \cr
#'   If mode_div = serial, same seed is used for all regions
#' @param xref Region cross-referencing data generated by template_region_xref() function\cr
#'   If set to NULL, calculated within function. Pre-calculate if running multiple times with same template,
#'   to reduce computation time.
#' '
#' @export
#'
Generate_VIMC_Burden_Dataset <- function(FOI_values = c(),R0_values = c(),input_data = list(),template = NULL,
                                         vaccine_efficacy = 1.0, time_inc = 1.0, mode_start = 1,
                                         mode_time = 0, n_reps = 1,deterministic = FALSE, p_severe_inf = 0.12,
                                         p_death_severe_inf = 0.39, YLD_per_case = 0.006486,
                                         mode_div = "default", n_nodes = 1, seed = NULL, xref = NULL){

  assert_that(input_data_check(input_data),
              msg = paste("Input data must be in standard format",
                          " (see https://mrc-ide.github.io/YEP/articles/CGuideAInputs.html)"))
  assert_that(all(c("region","year","age_min","age_max","life_exp") %in% names(template)))
  assert_that(mode_start %in% c(0,1),msg = "mode_start must be 0 or 1")
  assert_that(between(vaccine_efficacy,0.0,1.0),msg = "Vaccine efficacy must be between 0-1")
  assert_that(between(p_severe_inf,0.0,1.0),msg = "Severe infection rate must be between 0-1")
  assert_that(between(p_death_severe_inf,0.0,1.0),msg = "Fatality rate of severe infections must be between 0-1")
  assert_that(mode_div %in% c("parallel","serial","cluster"),
              msg = "mode_div must be 'default','serial' or 'cluster'")
  if(mode_div=="cluster"){assert_that(is.integer(n_nodes) & n_nodes>0,msg = "n_nodes must be a positive integer")}

  #Check that regions in template and input data match
  regions = regions_breakdown(template$region)
  assert_that(all(regions %in% input_data$region_labels),msg="Regions in template must be present in input data")
  input_data = input_data_truncate(input_data,regions)
  n_regions = length(regions)
  assert_that(length(dim(FOI_values)) == 2,msg = "FOI_values must be 2-D array")
  assert_that(length(dim(R0_values)) == 2,msg = "R0_values must be 2-D array")
  assert_that(dim(FOI_values)[1] == n_regions && dim(R0_values)[1] == n_regions,
              msg = "1st dimensions of FOI_values and R0_values must match no. regions to be modelled")
  n_t_pts_epi = dim(FOI_values)[2]
  n_years_popvac = length(input_data$years_labels)
  N_age = length(input_data$age_labels)

  #Cross-reference templates with input regions
  if(is.null(xref)){xref = template_region_xref(template,input_data$region_labels)}
  n_lines_total = nrow(template)

  #Set up data structures to take modelled data
  model_case_values = model_death_values = cohort_size = rep(0,n_lines_total)

  #Model all regions in parallel if parallel modes in use or set up inputs for serial running
  if(mode_div=="parallel"){
    model_output = Model_Run(FOI_spillover = FOI_values, R0 = R0_values,
                             vacc_data = input_data$vacc_data, pop_data = input_data$pop_data,
                             years_data = c(min(xref$year_data_begin):min(xref$year_end)),
                             start_SEIRV = NULL, mode_out = 4,
                             year0 = input_data$years_labels[1],mode_start = mode_start,
                             vaccine_efficacy = vaccine_efficacy, time_inc = time_inc, n_particles = n_reps,
                             n_threads = n_reps, deterministic = deterministic, mode_time = mode_time, seed = seed)
    years_out=model_output$year
    n_t_pts = length(years_out)
  } else {
    FOI_subsets = R0_subsets = vacc_data_subsets = pop_data_subsets = years_data_sets = list()
    for(n_region in 1:n_regions){
      FOI_subsets[[n_region]] = array(FOI_values[n_region,],dim=c(1,n_t_pts_epi))
      R0_subsets[[n_region]] = array(R0_values[n_region,],dim=c(1,n_t_pts_epi))
      vacc_data_subsets[[n_region]] = array(input_data$vacc_data[n_region,,],dim=c(1,n_years_popvac,N_age))
      pop_data_subsets[[n_region]] = array(input_data$pop_data[n_region,,],dim=c(1,n_years_popvac,N_age))
      years_data_sets[[n_region]] = c(xref$year_data_begin[n_region]:xref$year_end[n_region])
    }
    if(mode_div=="cluster"){
      cluster=makeCluster(n_nodes)
      model_output_all = clusterMap(cl = cluster,fun = Model_Run, FOI_spillover = FOI_subsets, R0 = R0_subsets,
                                    vacc_data = vacc_data_subsets,pop_data = pop_data_subsets,
                                    years_data = years_data_sets,
                                    MoreArgs = list(year0 = input_data$years_labels[1],
                                                    vaccine_efficacy = vaccine_efficacy,time_inc = time_inc,
                                                    mode_out = 4, mode_start = mode_start, start_SEIRV = NULL,
                                                    mode_time = mode_time, n_particles = n_reps, n_threads = 1 ,
                                                    deterministic = deterministic, seed = seed))
      stopCluster(cluster)
    }
  }

  #Save relevant output data from each region
  for(n_region in 1:n_regions){

    if(mode_div=="serial"){
      model_output = Model_Run(FOI_spillover = FOI_subsets[[n_region]], R0 = R0_subsets[[n_region]],
                               vacc_data = vacc_data_subsets[[n_region]], pop_data = pop_data_subsets[[n_region]],
                               years_data = years_data_sets[[n_region]], start_SEIRV = NULL, mode_out = 4,
                               year0 = input_data$years_labels[1],mode_start = mode_start,
                               vaccine_efficacy = vaccine_efficacy, time_inc = time_inc, n_particles = n_reps,
                               n_threads = n_reps, deterministic = deterministic, mode_time = mode_time, seed = seed)
      years_out=model_output$year
      n_t_pts = length(years_out)
      C_annual = array(model_output$C_annual[1,,,],dim=c(N_age,n_reps,n_t_pts))
    } else {
      if(mode_div=="cluster"){
        model_output = model_output_all[[n_region]]
        years_out = model_output_all[[n_region]]$year
        n_t_pts = length(years_out)
        C_annual = array(model_output_all[[n_region]]$C_annual[1,,,],dim=c(N_age,n_reps,n_t_pts))
      } else {
        C_annual = array(model_output$C_annual[n_region,,,],dim=c(N_age,n_reps,n_t_pts))
      }
    }

    case_line_list_region = xref$line_list[[n_region]]
    years_case = template$year[case_line_list_region]
    n_lines = length(case_line_list_region)
    age_pts = list()
    for(n_line in 1:n_lines){
      line = case_line_list_region[n_line]
      n_age_min = findInterval(template$age_min[line],input_data$age_labels)
      n_age_max = findInterval(template$age_max[line]-1,input_data$age_labels)
      age_pts[[n_line]] = c(n_age_min:n_age_max)
      cohort_size[line] = sum(input_data$pop_data[n_region,
                                                  input_data$years_labels == years_case[n_line],age_pts[[n_line]]])
    }

    for(n_rep in 1:n_reps){
      cases = deaths = rep(0,n_lines)
      for(n_line in 1:n_lines){
        year = years_case[n_line]
        t_pts = which(years_out == years_case[n_line])
        infs = sum(C_annual[age_pts[[n_line]],n_rep,t_pts])
        if(deterministic){
          cases[n_line] = infs*p_severe_inf
          deaths[n_line] = cases[n_line]*p_death_severe_inf
        } else {
          cases[n_line] = rbinom(1,floor(infs),p_severe_inf)
          deaths[n_line] = rbinom(1,cases[n_line],p_death_severe_inf)
        }
      }
      model_case_values[case_line_list_region] = model_case_values[case_line_list_region]+cases
      model_death_values[case_line_list_region] = model_death_values[case_line_list_region]+deaths
    }
  }

  model_case_values = model_case_values/n_reps
  model_death_values = model_death_values/n_reps
  model_YLL_values = model_death_values*template$life_exp
  model_dalys_values = (model_case_values*YLD_per_case)+model_YLL_values

  return(data.frame(disease = rep("YF",n_lines_total),year = template$year,age = template$age_min,
                    region_label1 = substr(template$region,1,3),region_label2 = template$region,
                    cohort_size = cohort_size,cases = model_case_values,dalys = model_dalys_values,
                    deaths = model_death_values,YLL = model_YLL_values))
}
